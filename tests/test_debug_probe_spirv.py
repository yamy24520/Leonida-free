"""runtime/src/debug_probe_spirv.h is the SPIR-V of the three LEONIDA_PROBE shaders in runtime/src
(debug_probe_fullscreen.vert, debug_probe_position.vert, debug_probe.frag). Each is compiled with

    glslangValidator -V --target-env vulkan1.2 -Os -g0 -o <name>.spv runtime/src/<source>

(glslang 16.6.0) and its little-endian words written as uint32_t literals.

    python -I tests/test_debug_probe_spirv.py           # checks the header
    python -I tests/test_debug_probe_spirv.py --write   # regenerates it"""
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "runtime", "src", "debug_probe_spirv.h")
GLSLANG_VERSION = "16.6.0"
# Array name in the header -> GLSL source in runtime/src.
SHADERS = [
    ("debug_probe_fullscreen_vs", "debug_probe_fullscreen.vert"),
    ("debug_probe_position_vs", "debug_probe_position.vert"),
    ("debug_probe_ps", "debug_probe.frag"),
]


def compile_words(glslang, source):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "probe.spv")
        run = subprocess.run([glslang, "-V", "--target-env", "vulkan1.2", "-Os", "-g0", "-o", out,
                              os.path.join(ROOT, "runtime", "src", source)], capture_output=True, text=True)
        if run.returncode:  # glslang names each file it compiles; print its output only when it fails
            raise RuntimeError(f"glslangValidator failed on {source}:\n{run.stdout}{run.stderr}")
        with open(out, "rb") as f:
            data = f.read()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def header_words():
    with open(HEADER, encoding="utf-8") as f:
        text = f.read()
    arrays = {}
    for name, body in re.findall(r"inline constexpr std::uint32_t (\w+)\[\] = \{(.*?)\};", text, re.S):
        arrays[name] = [int(x, 16) for x in re.findall(r"0x([0-9a-f]{8})u", body)]
    return arrays


def write_header(glslang):
    lines = [
        "// SPIR-V of the LEONIDA_PROBE shaders (debug_probe.h), generated by tests/test_debug_probe_spirv.py --write",
        f"// with glslang {GLSLANG_VERSION}; that test checks the words still match the GLSL. Each array is",
        "//   glslangValidator -V --target-env vulkan1.2 -Os -g0 -o <name>.spv runtime/src/<source>",
        "// as little-endian words. SPIR-V 1.5, as the translator emits; the runtime builds without a shader compiler.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace leonida {",
    ]
    for name, source in SHADERS:
        words = compile_words(glslang, source)
        lines.append("")
        lines.append(f"// runtime/src/{source}")
        lines.append(f"inline constexpr std::uint32_t {name}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + " ".join(f"0x{w:08x}u," for w in words[i:i + 8]))
        lines.append("};")
    lines += ["", "}  // namespace leonida", ""]
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def find_glslang():
    glslang = shutil.which("glslangValidator")
    if not glslang:
        return None, "glslangValidator is not on PATH"
    version = subprocess.run([glslang, "--version"], capture_output=True, text=True).stdout
    if GLSLANG_VERSION not in version:  # another glslang may emit other (equally valid) code
        return None, f"the header was generated with glslang {GLSLANG_VERSION}"
    return glslang, ""


class DebugProbeSpirv(unittest.TestCase):
    def test_header_is_spirv_1_5(self):
        arrays = header_words()
        self.assertEqual(sorted(arrays), sorted(name for name, _ in SHADERS))
        for name, words in arrays.items():
            self.assertEqual(words[0], 0x07230203, name)
            self.assertEqual(words[1], 0x00010500, name)

    def test_header_matches_the_glsl(self):
        glslang, why = find_glslang()
        if not glslang:
            self.skipTest(why)
        arrays = header_words()
        for name, source in SHADERS:
            words = compile_words(glslang, source)
            # Word 2 is the generator (glslang's version); the rest must be what the header holds.
            self.assertEqual(words[:2] + words[3:], arrays[name][:2] + arrays[name][3:], name)


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        glslang, why = find_glslang()
        if not glslang:
            sys.exit(why)
        write_header(glslang)
        sys.exit(0)
    unittest.main()
